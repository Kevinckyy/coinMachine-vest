import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';

export async function runBacktestChecks({base,run,command,evaluate,clickText,until,sleep,errors=[]}){
  const page=(fn,arg)=>evaluate('('+fn.toString()+')('+JSON.stringify(arg)+')');
  const field=label=>page(label=>document.querySelector('[aria-label='+CSS.escape(label)+']').value,label);
  const edit=values=>page(values=>{
    for(const [label,value] of Object.entries(values)){
      const input=document.querySelector('[aria-label='+CSS.escape(label)+']');
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,String(value));
      input.dispatchEvent(new Event('input',{bubbles:true}));
    }
  },values);
  const state=async()=> (await (await fetch(base+'/api/state')).json());
  const before=await state();
  await command('Page.navigate',{url:base+'/#backtest'});
  await until(()=>evaluate(`document.querySelector(\'.backtest-page\') && document.querySelectorAll(\'.backtest-cache-list strong\').length===4`),'backtest page and four cached native contracts');
  assert.equal(await field('回测品种'),'MNQ');
  assert.equal(await field('回测自动策略'),'random_entry');
  assert.equal(await evaluate(`document.querySelector('[aria-label="回测随机种子"]')===null`),true);
  assert.ok(await evaluate(`document.querySelector('[aria-label="回测随机规则"]').textContent.includes('PCG64DXSM')`));
  assert.equal(await field('回测每笔每边滑点 USD'),'0.4');
  assert.ok(await evaluate(`document.querySelector('[role="status"]')?.textContent.includes('旧滑点 0.1 bps')`),'legacy unit conversion is explained');
  assert.equal(await evaluate(`document.querySelector(\'.topbar .mode-switch button\').disabled`),true,'backtest page does not change live execution mode');
  await clickText('自动策略','aside button');
  await until(()=>evaluate(`document.querySelector(\'[aria-label=自动策略类型]\')?.value===\'random_entry\'`),'existing strategy is a named option');
  assert.equal(await evaluate(`document.querySelector(\'[aria-label=自动策略类型]\')?.selectedOptions[0].textContent`),'随机下单');
  await clickText('策略回测','aside button');
  await until(()=>evaluate(`document.querySelectorAll(\'.backtest-cache-list strong\').length===4`),'return to independent backtest');
  await clickText('拉取K线并保存到本地');
  await until(()=>evaluate(`document.querySelector(\'.backtest-job\')?.textContent.includes(\'已完成\')`),'fake history import completes');
  const jobsBeforeInvalid=(await (await fetch(base+'/api/backtests/meta')).json()).jobs.length;
  for(const invalid of ['',0,1.5,1000001]){
    await edit({'回测模拟账户数':invalid});
    if(invalid==='')assert.equal(await field('回测模拟账户数'),'','clearing the input must not insert zero');
    await clickText('使用本地K线开始回测');
    assert.ok(await evaluate(`document.querySelector(\'.error-banner\')?.textContent.includes(\'模拟账户数必须为1–1000000 之间的整数\')`),'account-count validation explains the range');
    assert.equal((await (await fetch(base+'/api/backtests/meta')).json()).jobs.length,jobsBeforeInvalid,'invalid parameters never create a backend task');
  }
  await edit({'回测模拟账户数':4,'回测每批账户数':2,'回测第一阶段目标':10,'回测第二阶段目标':6,
    '回测live 出金平仓目标':4,'回测分润到账延迟小时':48,'回测下单最小间隔秒':0,'回测下单最大间隔秒':0,
    '回测批次最小间隔秒':0,'回测批次最大间隔秒':0});
  await page(()=>{
    const el=document.querySelector('[aria-label='+CSS.escape('回测方向')+']');
    Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(el,'buy');
    el.dispatchEvent(new Event('change',{bubbles:true}));
  });
  await clickText('使用这份页面报价');
  assert.equal(await field('回测每笔每边滑点 USD'),'0.4');
  assert.equal(await evaluate(`document.querySelector('[aria-label="回测滑点单位 USD"]').getAttribute('aria-pressed')`),'true');
  await page(()=>document.querySelector('[aria-label="回测滑点单位 tick"]').click());
  await until(()=>evaluate(`!!document.querySelector('[aria-label="回测每边滑点 tick"]')`),'tick input appears');
  await edit({'回测每边滑点 tick':2});
  await page(()=>document.querySelector('[aria-label="回测滑点单位 USD"]').click());
  await until(()=>evaluate(`!!document.querySelector('[aria-label="回测每笔每边滑点 USD"]')`),'USD input appears');
  assert.equal(await field('回测每笔每边滑点 USD'),'0.4');
  assert.equal(await evaluate(`document.querySelector('[aria-label="回测每边滑点 bps"]')===null`),true);
  await clickText('使用本地K线开始回测');
  await until(()=>evaluate(`document.querySelectorAll('.backtest-batch-averages strong').length===9`),'summary statistics appear');
  await until(()=>evaluate(`document.querySelectorAll('[data-cash-line]').length===3`),'three cash curves');
  assert.equal(await evaluate(`document.querySelectorAll('.backtest-stage-statistics tbody tr').length`),3);
  assert.ok(await evaluate(`document.querySelector('[aria-label="统计每号平均单数"]')?.textContent!=='—'`));
  assert.ok(await evaluate(`document.querySelector('[aria-label="统计平均持仓时间"]')?.textContent!=='—'`));
  assert.equal(await evaluate(`document.querySelectorAll('.backtest-history,.backtest-selected-round,.backtest-assumptions,.backtest-pagination').length`),0,'individual and per-round detail views removed');
  assert.equal(await evaluate(`document.body.textContent.includes('模拟成交明细')`),false);
  await page(()=>document.querySelector('[aria-label="资金曲线不含手续费"]').click());
  assert.equal(await evaluate(`document.querySelector('[aria-label="资金曲线不含手续费"]').getAttribute('aria-pressed')`),'true');
  assert.equal(await evaluate(`document.querySelectorAll('[data-cash-line]').length`),3);
  await page(()=>document.querySelector('[aria-label="资金曲线含手续费"]').click());
  const runs=await (await fetch(base+'/api/backtests/runs')).json();
  assert.equal(runs.runs.length,1);
  await command('Page.navigate',{url:base+'/#backtest'});
  await until(()=>evaluate(`document.querySelectorAll('.backtest-batch-averages strong').length===9`),'summary restores after reload');
  assert.match((await (await fetch(base+'/api/backtests/meta')).json()).saved_form.seed,/^0x[0-9a-f]{32}$/);
  assert.equal(await field('回测每笔每边滑点 USD'),'0.4');
  await edit({'回测模拟账户数':10000});
  await clickText('使用本地K线开始回测');
  await until(async()=> (await (await fetch(base+'/api/backtests/runs')).json()).runs.length===2,'10000-account result saved');
  await until(()=>evaluate(`document.querySelector('.backtest-job')?.textContent.includes('已完成')`),'10000-account result completes');
  let latest=(await (await fetch(base+'/api/backtests/meta')).json()).batches[0];
  let summary=await (await fetch(base+'/api/backtests/batches/'+latest.id+'?summary_only=1')).json();
  assert.equal(summary.summary.trading.total_accounts,10000);assert.deepEqual(summary.rows,[]);
  await page(()=>document.querySelector('[aria-label="回测无限账户"]').click());
  await edit({'回测测试轮数':3,'回测并行任务数':2,'回测杠杆':49});
  const beforeTiming=(await (await fetch(base+'/api/backtests/runs')).json()).runs.length;
  await clickText('测量单轮耗时');
  await until(()=>evaluate(`[...document.querySelectorAll('.backtest-time-estimate strong')].every(e=>e.textContent!=='—')`),'duration estimates');
  assert.equal((await (await fetch(base+'/api/backtests/runs')).json()).runs.length,beforeTiming);
  await until(()=>evaluate(`document.querySelector('.backtest-plan button.primary')?.disabled===false`),'measurement completed before starting batch');
  await clickText('开始 3 轮随机种子回测');
  await until(async()=> (await (await fetch(base+'/api/backtests/meta')).json()).batches[0].config.rounds===3&&(await (await fetch(base+'/api/backtests/meta')).json()).batches[0].status==='completed','parallel summary completes');
  await until(()=>evaluate(`document.querySelector('.backtest-batch')?.textContent.includes('已完成 3 / 3 轮')`),'completed rounds shown');
  latest=(await (await fetch(base+'/api/backtests/meta')).json()).batches[0];
  summary=await (await fetch(base+'/api/backtests/batches/'+latest.id+'?summary_only=1')).json();
  assert.equal(summary.summary.parallel_workers,2);assert.deepEqual(summary.rows,[]);
  const seedRows=await (await fetch(base+'/api/backtests/batches/'+latest.id)).json();
  const seeds=seedRows.rows.map(r=>r.seed);assert.equal(new Set(seeds).size,3);
  assert.ok(seeds.every(s=>/^0x[0-9a-f]{32}$/.test(s)));
  assert.equal(summary.summary.cash_curves.with_fees.rounds,3);
  assert.equal(summary.summary.cash_curves.without_fees.rounds,3);
  assert.equal(summary.summary.metrics.pending_payout.mean,0);
  assert.ok(summary.summary.metrics.settled_after_cutoff.mean>0);
  assert.ok(summary.summary.settlement.settlement_end>summary.summary.settlement.trading_end);
  assert.ok(await evaluate(`document.querySelector('.backtest-batch').textContent.includes('截止后停止交易')`));
  await page(()=>{const svg=document.querySelector('[aria-label="最好最差平均资金曲线"]');const box=svg.getBoundingClientRect();svg.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,clientX:box.right,clientY:box.top+100}));});
  await page(()=>document.querySelector('[aria-label="资金曲线不含手续费"]').click());
  await until(()=>evaluate(`document.querySelector('[aria-label="资金曲线不含手续费"]').getAttribute('aria-pressed')==='true'`),'fee-free curve selected');
  const expected=summary.summary.cash_curves.without_fees.average.at(-1).value.toLocaleString('en-US',{maximumFractionDigits:2,minimumFractionDigits:2});
  assert.ok(await page(expected=>document.querySelector('.backtest-cash-legend').textContent.includes(expected),expected));
  assert.equal(await evaluate(`performance.getEntriesByType('resource').filter(x=>x.name.includes('/api/backtests/runs/')).length`),0,'UI does not fetch individual results');
  await page(()=>document.querySelector('.backtest-batch').scrollIntoView({block:'start'}));
  const shot=await command('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
  await writeFile(path.join(run,'summary-desktop.png'),Buffer.from(shot.data,'base64'));
  await page(()=>document.querySelector('.backtest-cash-heading').scrollIntoView({block:'start'}));
  const curveShot=await command('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
  await writeFile(path.join(run,'cash-curves.png'),Buffer.from(curveShot.data,'base64'));
  await command('Page.navigate',{url:base+'/#backtest'});
  await until(()=>evaluate(`document.querySelector('.backtest-batch')?.textContent.includes('已完成 3 / 3 轮')`),'batch statistics persist');
  assert.equal(await field('回测测试轮数'),'3');
  await edit({'回测测试轮数':1000});
  await until(()=>evaluate(`document.querySelector('.backtest-plan button.primary')?.textContent.includes('1,000') && document.querySelector('.backtest-plan button.primary')?.disabled===false`),'edited round count rendered and ready');
  await clickText('开始 1,000 轮随机种子回测');await clickText('停止本次测试');
  await until(()=>evaluate(`document.querySelector('.backtest-job')?.textContent.includes('已停止')`),'cancellation completes');
  const after=await state();assert.deepEqual(after.positions,before.positions);assert.equal(after.strategy.status,before.strategy.status);assert.deepEqual(after.bridge.jobs,before.bridge.jobs);
  const audit=JSON.parse(await readFile(path.join(run,'smoke.history-reads.json'),'utf8'));
  assert.ok(audit.every(x=>x.method==='GET'&&['/api/status','/api/symbols','/api/resolve','/api/history'].includes(x.path)));
  await command('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:false});await sleep(500);
  const layout=await evaluate('({width:document.body.scrollWidth,viewport:innerWidth})');assert.ok(layout.width<=layout.viewport+2);
  const mobile=await command('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});await writeFile(path.join(run,'summary-mobile.png'),Buffer.from(mobile.data,'base64'));
  assert.deepEqual(errors,[]);
  return {ok:true,checks:['summary-only result page','no per-round or individual detail requests','weighted trade and stage averages','best/worst/mean cash curves','fee-inclusive and fee-free curve switch','10000 accounts','infinite accounts','parallel rounds','timing estimates','summary persistence','cancellation','no live trading state changed','responsive layout'],screenshots:[path.join(run,'summary-desktop.png'),path.join(run,'cash-curves.png'),path.join(run,'summary-mobile.png')]};
}
